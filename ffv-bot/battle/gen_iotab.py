#!/usr/bin/env python3
"""Generate iotab.h: per-opcode count of internal (non-bus) cycles = documented 65816 cycles (M=X=1, DL=0, no page cross,
branch not taken) minus the bus accesses the interpreter really performs for that opcode.  Re-run after changing cpu65816.c."""
import os, sys, ctypes
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cpu
from dis65816 import OPS
L = cpu.L
L.sim_step1.argtypes = [ctypes.c_void_p]; L.sim_step1.restype = ctypes.c_int

READ = {"ORA","AND","EOR","ADC","SBC","CMP","LDA","LDX","LDY","CPX","CPY","BIT"}
STORE = {"STA","STX","STY","STZ"}
RMW = {"ASL","LSR","ROL","ROR","INC","DEC","TSB","TRB"}
RT = {"imm":2,"dp":3,"dp,X":4,"dp,Y":4,"abs":4,"abs,X":4,"abs,Y":4,"(dp,X)":6,"(dp),Y":5,"(dp)":5,"[dp]":6,"[dp],Y":6,"long":5,"long,X":5,"sr,S":4,"(sr,S),Y":7}
ST = dict(RT, **{"abs,X":5,"abs,Y":5,"(dp),Y":6})
RM = {"A":2,"dp":5,"dp,X":6,"abs":6,"abs,X":7}
OTHER = {"BRK":8,"COP":8,"PHP":3,"PHA":3,"PHX":3,"PHY":3,"PHB":3,"PHK":3,"PHD":4,"PLP":4,"PLA":4,"PLX":4,"PLY":4,"PLB":4,"PLD":5,
         "PEA":5,"PEI":6,"PER":6,"JSR":6,"JSL":8,"RTS":6,"RTL":6,"RTI":7,"MVN":7,"MVP":7,"WAI":3,"STP":3,"XBA":3,"REP":3,"SEP":3,
         "BRA":2,"BRL":4,"WDM":2}
def cycles(op):
    mn, _, mode = OPS[op].partition(" ")
    mode = {"#M":"imm","#X":"imm","#":"imm"}.get(mode, mode)
    if mn == "JMP": return {"abs":3,"(abs)":5,"(abs,X)":6}[mode]
    if mn == "JML": return {"long":4,"[abs]":6}[mode]
    if mn == "JSR" and mode == "(abs,X)": return 8
    if mn in OTHER: return OTHER[mn]
    if mn in READ: return RT[mode]
    if mn in STORE: return ST[{"dp,Y":"dp,Y"}.get(mode, mode)]
    if mn in RMW: return RM[mode]
    if mn.startswith("B") and mode == "r": return 2
    return 2      # implied / register transfers / flag ops / NOP / XCE

def observed_nb(op):
    m = cpu.Machine(); m.setreg(cpu.R_E, 0)
    w = m.wram
    for i, b in enumerate([op, 0x00, 0x20, 0x7E, 0, 0, 0, 0]): w[0x1000 + i] = b
    for i in range(0x20): w[0x2000 + i] = 0
    w[0x2000] = 0x00; w[0x2001] = 0x20; w[0x2002] = 0x7E     # pointers -> 7E:2000 region
    m.setreg(cpu.R_PB, 0x7E); m.setreg(cpu.R_PC, 0x1000); m.setreg(cpu.R_DB, 0x7E); m.setreg(cpu.R_D, 0)
    m.setreg(cpu.R_S, 0x1FFF); m.setreg(cpu.R_P, 0x34 | 0x20 | 0x10 | 0x0F & 0)  # M=X=1, I set; Z=C=N=V=0 -> BNE taken? handled below
    m.setreg(cpu.R_P, 0x34 | 0x02 | 0x01)   # Z and C set: BEQ/BCS would take, BNE/BCC not; fixed up by taking the max below
    m.setreg(cpu.R_X, 0); m.setreg(cpu.R_Y, 0); m.setreg(cpu.R_NMITIMEN, 0)
    if op == 0x40: w[0x1FFD] = 0x34; w[0x1FFE] = 0; w[0x1FFF] = 0x10; w[0x1FFC] = 0x00; m.setreg(cpu.R_S, 0x1FFB)
    m.setreg(cpu.R_CYCSCALE, 0); L.sim_setreg(m.p, 17, 0)
    if L.sim_step1(m.p) < 0: return None
    return L.sim_reg(m.p, 17)

def main():
    vals, bad = [], []
    for op in range(256):
        T = cycles(op); nb = observed_nb(op)
        # branches: documented 2 cycles when not taken; Z/C set above makes some taken -> subtract the taken fetch
        if nb is None: bad.append(op); vals.append(0); continue
        mn = OPS[op].split()[0]
        io = T - nb
        if io < 0: bad.append((hex(op), OPS[op], T, nb)); io = 0
        vals.append(io)
    out = "/* generated by gen_iotab.py: internal cycles per opcode (x6 master cycles each) */\nstatic const uint8_t IOT[256] = {\n"
    out += "".join("  " + ",".join(str(v) for v in vals[i:i + 16]) + ",\n" for i in range(0, 256, 16)) + "};\n"
    open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "iotab.h"), "w").write(out)
    print("anomalies:", bad)
if __name__ == "__main__": main()
